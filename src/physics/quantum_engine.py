# ==============================================================================
# 1. Quantum Event Data Containers
# ==============================================================================

@dataclass
class QuantumBatch:
    """Contains a newly generated batch of discrete photon detection events.

    Attributes:
        x_hits: 1D float32 NumPy array of horizontal impact positions in meters.
        y_hits: 1D float32 NumPy array of vertical impact positions in meters.
        slit_tags: 1D int8 array indicating slit origin:
            0 = Coherent / Indistinguishable (superposition state).
            1 = Passed through Slit 1 (Left).
            2 = Passed through Slit 2 (Right).
        count: Total number of detection events in this batch.
        generation_time_ms: Computation time taken to sample the batch in milliseconds.
    """

    x_hits: np.ndarray
    y_hits: np.ndarray
    slit_tags: np.ndarray
    count: int
    generation_time_ms: float


# ==============================================================================
# 2. Virtual Detector Screen Accumulator
# ==============================================================================

class QuantumAccumulator:
    """Simulates a CMOS or phosphor detector screen accumulating discrete particle hits."""

    def __init__(self, max_retained_hits: int = 150_000, histogram_bins: int = 200) -> None:
        """Initializes the detector accumulator.

        Args:
            max_retained_hits: Maximum number of recent coordinate pairs stored
                for point-cloud rendering in OpenGL viewports.
            histogram_bins: Number of spatial bins for the 1D cross-section histogram.
        """
        self.max_retained_hits: int = max_retained_hits
        self.histogram_bins: int = histogram_bins

        self.total_photons: int = 0
        self.photons_slit1: int = 0
        self.photons_slit2: int = 0

        # Circular buffer arrays for recent hit coordinates
        self.hit_x: np.ndarray = np.empty(max_retained_hits, dtype=np.float32)
        self.hit_y: np.ndarray = np.empty(max_retained_hits, dtype=np.float32)
        self.hit_tags: np.ndarray = np.empty(max_retained_hits, dtype=np.int8)
        self.buffer_count: int = 0
        self.buffer_write_idx: int = 0

        # Accumulated 1D cross-section histogram
        self.hist_1d_counts: np.ndarray = np.zeros(histogram_bins, dtype=np.float64)
        self.hist_1d_bin_centers: np.ndarray = np.zeros(histogram_bins, dtype=np.float32)
        self.current_span: float = 0.0

    def reset(self, target_span: float) -> None:
        """Clears all accumulated photon hits and resets detector state.

        Args:
            target_span: Full physical width/height of the observation plane in meters.
        """
        self.total_photons = 0
        self.photons_slit1 = 0
        self.photons_slit2 = 0
        self.buffer_count = 0
        self.buffer_write_idx = 0
        self.current_span = target_span

        self.hist_1d_counts.fill(0.0)
        edges = np.linspace(-0.5 * target_span, 0.5 * target_span, self.histogram_bins + 1, dtype=np.float32)
        self.hist_1d_bin_centers = 0.5 * (edges[:-1] + edges[1:])

    def add_batch(self, batch: QuantumBatch, target_span: float) -> None:
        """Records a new batch of photon hits into the detector memory.

        Args:
            batch: QuantumBatch instance containing coordinates and tags.
            target_span: Full physical width of the detector screen in meters.
        """
        if abs(self.current_span - target_span) > 1e-9:
            self.reset(target_span)

        n = batch.count
        if n <= 0:
            return

        self.total_photons += n

        # Count tagged photons
        n_s1 = int(np.count_nonzero(batch.slit_tags == 1))
        n_s2 = int(np.count_nonzero(batch.slit_tags == 2))
        self.photons_slit1 += n_s1
        self.photons_slit2 += n_s2

        # 1. Update circular buffer for point-cloud display
        if n >= self.max_retained_hits:
            # Entire buffer overwritten with latest hits
            self.hit_x[:] = batch.x_hits[-self.max_retained_hits:]
            self.hit_y[:] = batch.y_hits[-self.max_retained_hits:]
            self.hit_tags[:] = batch.slit_tags[-self.max_retained_hits:]
            self.buffer_count = self.max_retained_hits
            self.buffer_write_idx = 0
        else:
            space_left = self.max_retained_hits - self.buffer_write_idx
            if n <= space_left:
                idx_end = self.buffer_write_idx + n
                self.hit_x[self.buffer_write_idx:idx_end] = batch.x_hits
                self.hit_y[self.buffer_write_idx:idx_end] = batch.y_hits
                self.hit_tags[self.buffer_write_idx:idx_end] = batch.slit_tags
                self.buffer_write_idx = (self.buffer_write_idx + n) % self.max_retained_hits
            else:
                # Wrap-around write
                self.hit_x[self.buffer_write_idx:] = batch.x_hits[:space_left]
                self.hit_y[self.buffer_write_idx:] = batch.y_hits[:space_left]
                self.hit_tags[self.buffer_write_idx:] = batch.slit_tags[:space_left]

                rem = n - space_left
                self.hit_x[:rem] = batch.x_hits[space_left:]
                self.hit_y[:rem] = batch.y_hits[space_left:]
                self.hit_tags[:rem] = batch.slit_tags[space_left:]
                self.buffer_write_idx = rem

            self.buffer_count = min(self.max_retained_hits, self.buffer_count + n)

        # 2. Update 1D horizontal histogram (using hits close to center |y| <= 0.2 * span)
        y_filter = np.abs(batch.y_hits) <= (0.2 * target_span)
        filtered_x = batch.x_hits[y_filter]

        if len(filtered_x) > 0:
            hist, _ = np.histogram(
                filtered_x,
                bins=self.histogram_bins,
                range=(-0.5 * target_span, 0.5 * target_span),
            )
            self.hist_1d_counts += hist

    def get_active_hits(self) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
        """Returns the currently active point-cloud coordinate arrays.

        Returns:
            Tuple of (x_array, y_array, slit_tags_array).
        """
        count = self.buffer_count
        return (
            self.hit_x[:count],
            self.hit_y[:count],
            self.hit_tags[:count],
        )

    def get_normalized_1d_histogram(self) -> Tuple[np.ndarray, np.ndarray]:
        """Returns normalized 1D histogram curve for plotting against theory.

        Returns:
            Tuple of (bin_centers_x, normalized_counts_in_range_0_to_1).
        """
        max_count = np.max(self.hist_1d_counts)
        if max_count > 0.0:
            norm_counts = (self.hist_1d_counts / max_count).astype(np.float32)
        else:
            norm_counts = np.zeros_like(self.hist_1d_counts, dtype=np.float32)

        return self.hist_1d_bin_centers, norm_counts


# ==============================================================================
# 3. Quantum Sampling Engine Class
# ==============================================================================

class QuantumEngine:
    """High-performance Monte Carlo sampler for quantum particle detection."""

    def __init__(self, force_cpu: bool = False) -> None:
        """Initializes the quantum Monte Carlo engine."""
        self.use_gpu: bool = CUPY_AVAILABLE and (not force_cpu)
        self.device_name: str = _DEV_NAME if self.use_gpu else "CPU (NumPy)"

        # Cached CDF data for repeated sampling at identical probability fields
        self._cached_pdf_id: int = 0
        self._cached_cdf = None

    def sample_batch(
        self,
        count: int,
        intensity_2d: np.ndarray,
        x_coords: np.ndarray,
        y_coords: np.ndarray,
        which_way_active: bool = False,
    ) -> QuantumBatch:
        """Generates a batch of stochastic particle detections via Born's rule.

        Args:
            count: Number of particle detection events to generate.
            intensity_2d: 2D float32 array of relative probability density P(x, y).
            x_coords: 1D array of horizontal spatial grid coordinates in meters.
            y_coords: 1D array of vertical spatial grid coordinates in meters.
            which_way_active: If True, tags each particle with slit origin (1 vs 2).

        Returns:
            QuantumBatch containing impact coordinates and slit tags.
        """
        if count <= 0:
            empty_f = np.empty(0, dtype=np.float32)
            empty_i = np.empty(0, dtype=np.int8)
            return QuantumBatch(empty_f, empty_f, empty_i, 0, 0.0)

        t_start = time.perf_counter()

        if self.use_gpu:
            x_hits, y_hits, tags = self._sample_gpu(
                count, intensity_2d, x_coords, y_coords, which_way_active
            )
        else:
            x_hits, y_hits, tags = self._sample_cpu(
                count, intensity_2d, x_coords, y_coords, which_way_active
            )

        t_elapsed_ms = (time.perf_counter() - t_start) * 1000.0

        return QuantumBatch(
            x_hits=x_hits,
            y_hits=y_hits,
            slit_tags=tags,
            count=count,
            generation_time_ms=t_elapsed_ms,
        )

    # ==========================================================================
    # GPU Sampling Implementation (CuPy)
    # ==========================================================================

    def _sample_gpu(
        self,
        count: int,
        intensity_2d: np.ndarray,
        x_coords: np.ndarray,
        y_coords: np.ndarray,
        which_way_active: bool,
    ) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
        """Runs 2D inverse CDF sampling on NVIDIA GPU silicon."""
        grid_h, grid_w = intensity_2d.shape
        dx = float(x_coords[1] - x_coords[0]) if len(x_coords) > 1 else 1e-5
        dy = float(y_coords[1] - y_coords[0]) if len(y_coords) > 1 else 1e-5

        # Upload probability distribution to GPU VRAM
        p_gpu = cp.asarray(intensity_2d, dtype=cp.float32).ravel()
        p_sum = float(p_gpu.sum())
        if p_sum <= 0.0:
            p_gpu = cp.ones_like(p_gpu) / p_gpu.size
        else:
            p_gpu /= p_sum

        # Calculate Cumulative Distribution Function (CDF)
        cdf = cp.cumsum(p_gpu)

        # Generate uniform random variates U(0, 1) directly on GPU
        u = cp.random.uniform(0.0, 1.0, count, dtype=cp.float32)

        # Binary search: map random values to flattened grid pixel indices
        pixel_indices = cp.searchsorted(cdf, u)
        pixel_indices = cp.clip(pixel_indices, 0, (grid_h * grid_w) - 1)

        # Decompose 1D flattened index into 2D row (y) and column (x)
        row_indices = pixel_indices // grid_w
        col_indices = pixel_indices % grid_w

        # Upload coordinate vectors to GPU
        x_coords_gpu = cp.asarray(x_coords, dtype=cp.float32)
        y_coords_gpu = cp.asarray(y_coords, dtype=cp.float32)

        # Sub-pixel continuous spatial jitter in range [-0.5*dx, +0.5*dx]
        jitter_x = (cp.random.uniform(0.0, 1.0, count, dtype=cp.float32) - 0.5) * dx
        jitter_y = (cp.random.uniform(0.0, 1.0, count, dtype=cp.float32) - 0.5) * dy

        x_sampled = x_coords_gpu[col_indices] + jitter_x
        y_sampled = y_coords_gpu[row_indices] + jitter_y

        # Slit tagging under which-way measurement
        if which_way_active:
            # Particles with x < 0 originate primarily from Slit 1 (Left),
            # particles with x >= 0 from Slit 2 (Right)
            slit_tags = cp.where(x_sampled < 0.0, cp.int8(1), cp.int8(2))
        else:
            slit_tags = cp.zeros(count, dtype=cp.int8)

        cp.cuda.Stream.null.synchronize()

        # Transfer sampled coordinates to host CPU
        return (
            cp.asnumpy(x_sampled),
            cp.asnumpy(y_sampled),
            cp.asnumpy(slit_tags),
        )

    # ==========================================================================
    # CPU Sampling Implementation (NumPy)
    # ==========================================================================

    def _sample_cpu(
        self,
        count: int,
        intensity_2d: np.ndarray,
        x_coords: np.ndarray,
        y_coords: np.ndarray,
        which_way_active: bool,
    ) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
        """Runs 2D inverse CDF sampling on CPU NumPy memory."""
        grid_h, grid_w = intensity_2d.shape
        dx = float(x_coords[1] - x_coords[0]) if len(x_coords) > 1 else 1e-5
        dy = float(y_coords[1] - y_coords[0]) if len(y_coords) > 1 else 1e-5

        p_flat = intensity_2d.ravel().astype(np.float64)
        p_sum = p_flat.sum()
        if p_sum <= 0.0:
            p_flat = np.ones_like(p_flat) / p_flat.size
        else:
            p_flat /= p_sum

        cdf = np.cumsum(p_flat)

        u = np.random.uniform(0.0, 1.0, count).astype(np.float64)
        pixel_indices = np.searchsorted(cdf, u)
        pixel_indices = np.clip(pixel_indices, 0, (grid_h * grid_w) - 1)

        row_indices = pixel_indices // grid_w
        col_indices = pixel_indices % grid_w

        jitter_x = (np.random.uniform(0.0, 1.0, count).astype(np.float32) - 0.5) * dx
        jitter_y = (np.random.uniform(0.0, 1.0, count).astype(np.float32) - 0.5) * dy

        x_sampled = x_coords[col_indices] + jitter_x
        y_sampled = y_coords[row_indices] + jitter_y

        if which_way_active:
            slit_tags = np.where(x_sampled < 0.0, np.int8(1), np.int8(2))
        else:
            slit_tags = np.zeros(count, dtype=np.int8)

        return x_sampled, y_sampled, slit_tags
