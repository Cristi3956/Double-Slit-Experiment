r"""Quantum Monte Carlo photon sampling and particle-by-particle detector accumulation.

This module implements the quantum mechanical probabilistic interpretation
of the double-slit experiment (Born's rule):
    P(x, y) = |psi(x, y, L)|^2 / \iint |psi(x', y', L)|^2 dx' dy'

Individual photons or quantum particles arrive stochastically at the detector
screen. Over time, the discrete particle clicks accumulate to form the continuous
interference fringe pattern, illustrating particle-wave duality.

Key Capabilities:
-----------------
1. GPU Inverse Cumulative Distribution Function (CDF) Sampling:
   Flattens the 2D irradiance distribution P(x, y), calculates its 1D CDF, and
   uses binary search (cp.searchsorted) with uniform random variates U(0, 1)
   to sample thousands of particle hits per millisecond on the RTX 3060.

2. Sub-Pixel Jitter:
   Continuous spatial coordinates (x_m, y_m) are generated by adding uniform
   sub-pixel jitter to prevent discrete pixel grid artifacts.

3. Quantum Measurement & Path Tagging ('Which-Way'):
   When which-way detection is active:
   - Wavefunction collapse removes mutual interference between the slits.
   - Each photon is physically tagged with the slit it traversed (Slit 1 or Slit 2).
   - The user can visualize the separate corpuscular distributions landing on the screen.

4. Detector Accumulator:
   Maintains a virtual phosphor / CMOS detector screen with persistent hit history,
   a 2D accumulation density map, and a 1D cross-section histogram for live
   plotting against the theoretical curve.
"""

